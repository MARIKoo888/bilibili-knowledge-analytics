-- ============================================================
-- 业务问题：Q2 视频时长与播放量的关系 —— 多长的视频播放中位数更高？
-- 指标口径：因变量 = 播放量中位数；自变量 = 时长桶（5 档，单位秒）
-- 对比基准：全区播放中位数 41,532
-- 结论：控制分区（只看职业职场 n=173）后，全量版本的两个高点消失：
--   <3分钟 61,825→14,980（-76%），15–30分钟 77,938→25,328（-67%），
--   说明它们由其他分区的短视频（娱乐/搞笑类）贡献，非时长效应。
--   唯一稳健结论：8–15 分钟播放中位数 46,597，为 3–8 分钟(20,554)的 2.3 倍。
-- → 行动建议：职场垂类的内容时长应控制在 8–15 分钟；做 3 分钟以内或 15 分钟以上
> 时长需谨慎。
-- 已知局限：① 未控制分区与 UP 主粉丝量（粉丝数据未采集）；
--           ② coin/share 缺失，互动率只能用(点赞+收藏)/播放；
--           ③ 样本偏向爆款（排行榜+搜索前几页）
-- ============================================================


-- 【第 1 层】base：明细表。一行 = 一条视频。
-- 这一层只做一件事：把"秒数"翻译成"时长桶"这个新列。
-- ⚠️ 这一层绝对不能出现 COUNT/SUM/AVG（那是聚合），否则报 only_full_group_by。
WITH base AS (
    SELECT
        view_cnt,                                                    -- 要用的指标：播放量
        CASE WHEN duration_sec < 180  THEN '1_小于3分钟'              -- 0~179 秒
             WHEN duration_sec < 480  THEN '2_3到8分钟'               -- 180~479 秒
             WHEN duration_sec < 900  THEN '3_8到15分钟'              -- 480~899 秒
             WHEN duration_sec < 1800 THEN '4_15到30分钟'             -- 900~1799 秒
             ELSE                          '5_大于30分钟'             -- 1800 秒以上
        END AS 时长桶                                                -- 起个名字，后面要靠它分组
    FROM video
    WHERE is_duration_outlier = 0         -- 排除 >3 小时的直播回放/课程合集
    AND sub_zone = '职业职场'                            --加筛选条件
),


-- 【第 2 层】r：窗口层。一行 = 一条视频（行数不变！）。
-- 这一层也只做"加列"，不做聚合：
--   rn  = 同一时长桶内，按播放量从小到大排，这条排第几
--   cnt = 同一时长桶内，一共有几条
-- 求中位数就靠这两列（正中间那 1~2 行的 rn 会被第 3 层挑出来）。
r AS (
    SELECT
        时长桶,
        view_cnt,
        ROW_NUMBER() OVER (PARTITION BY 时长桶 ORDER BY view_cnt) AS rn,
        COUNT(*)     OVER (PARTITION BY 时长桶)                   AS cnt
    FROM base
)


-- 【第 3 层】最终聚合。一行 = 一个时长桶（行数变少！）。
-- GROUP BY 把每个桶的多行压成一行，然后：
--   中位数 = 只对"正中间那 1~2 行"求平均（CASE WHEN 筛选 + AVG 自动忽略 NULL）
--   n     = 这个桶的样本量
SELECT
    时长桶,
    MAX(cnt) AS n,                                                   -- 组内条数（cnt 每行都一样，取 MAX 就是取那个值）
    ROUND(AVG(CASE WHEN rn IN (FLOOR((cnt+1)/2), CEIL((cnt+1)/2))    -- 只保留正中间那 1~2 行
                   THEN view_cnt                                     -- 其它行返回 NULL
              END))   AS 播放中位数                                  -- AVG 忽略 NULL，等价于"取中间值"
FROM r
GROUP BY 时长桶
-- 按桶名排序，才是 1→5 的顺序（ORDER BY 写在最后一行，行尾不要再跟注释）
ORDER BY 时长桶;