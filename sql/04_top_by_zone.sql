-- 业务问题：Q2 各分区的头部爆款长什么样？它们的共同特征是什么？
-- 指标口径：排名 = 分区内按播放量降序的 ROW_NUMBER；仅纳入 n>=10 的分区
-- 对比基准：分区内部排名（不跨区比，因为分区规模差异巨大）
-- 结论：
--   ① 职业职场 Top10 中 6 条为"面试"内容、1 条简历、1 条谈薪，
--      职场软技能（沟通/情商）仅 1 条上榜 → 爆款集中在"求职硬技能"。
--   ② Top10 有 6 条时长落在 8–18 分钟，与 SQL#3"8–15分钟最优"交叉验证一致。
--   ③ 关键发现：求职类内容大量溢出到其他分区 ——
--      「日常」Top10 全部为求职内容（转行/找工作/低学历出路），
--      「计算机技术」Top10 全部为简历/面试内容。
--      → 若只按「职业职场」分区定位选题，会漏掉一半以上求职流量。
--   ④ 标题模式：具体人群（普通人/零基础/秋招）+ 具体痛点（一面试就挂）+ 承诺结果（看这就够/背下来）。
-- 已知局限：① 播放为快照值；② 仅取 Top10，不代表分区全貌；③ 未控制 UP 主粉丝量
-- ============================================================


WITH t AS (
    SELECT
        sub_zone,
        title,
        view_cnt,
        duration_sec,
        -- TODO 1：算「每个分区内部的播放排名」，排第一的是播放最高的
        --   提示：ORDER BY view_cnt 要加 DESC（降序），否则排的是"最小"在前
        ROW_NUMBER() OVER (PARTITION BY sub_zone ORDER BY view_cnt DESC) AS rk,

        -- 这个已给：该分区总条数（用于过滤小样本分区）
        COUNT(*) OVER (PARTITION BY sub_zone) AS n
    FROM video
    WHERE is_duration_outlier = 0
)
SELECT
    sub_zone,
    rk,
    view_cnt,
    ROUND(duration_sec / 60.0, 1) AS 时长分钟,   -- 秒转分钟，保留1位小数（60.0 是为了不丢小数）
    title
FROM t
-- TODO 2：只保留 rk <= 10 且 n >= 10 的行
--   提示：AND
WHERE rk<=10 AND n>=10
ORDER BY sub_zone, rk;