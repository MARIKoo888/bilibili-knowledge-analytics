-- ============================================================
-- 业务问题：Q3 前哨 / Q2 补充 —— 不同分区的"互动结构"是否不同？
--   核心假设（来自生活观察）：职场类内容用户会"收藏但不点赞"，
--   因为把内容当工具存起来、而不是当娱乐欣赏。
-- 指标口径：
--   收藏率 = 每条视频 (fav_cnt / view_cnt) 之后取平均
--   点赞率 = 每条视频 (like_cnt / view_cnt) 之后取平均
--   收藏/点赞 比值 = 收藏率 ÷ 点赞率（>1 表示"收藏多于点赞"）
--   分母说明：用 AVG(单条比率) 而非 SUM/SUM。后者等价于按播放加权，
--            会被爆款主导；本分析要回答"典型视频被收藏的概率"，所以用普通平均。
-- 对比基准：各二级分区横向比较（仅纳入 n>=10 的分区）
-- 结论：职业职场是知识区唯一"收藏率高于点赞率"的细分
--   （收藏 3.39% vs 点赞 1.93%，比值 1.76；其他分区比值 0.41–0.93）。
--   → 行动建议：职场垂类应以"收藏率"而非"点赞率"作为内容质量核心指标。
-- 二次检验（语句3）：5 个关键词的收藏率差异显著（转行 1.89% → 职场沟通 5.64%）；
--   符合"方法类 > 资讯类"的方向（职场沟通最高、转行最低），但"简历修改(3.41%)"
--   并未高于"求职面试(3.69%)"，与预期有偏差，如实记录。
-- 已知局限：
--   1) 样本偏向爆款（排行榜+搜索前几页），收藏率可能被高估；
--   2) 收藏是累计值，老视频更有优势 → 已用 view_cnt>1000 过滤极小播放；
--   3) coin_cnt / share_cnt 缺失，无法算综合互动率；
--   4) 各分区样本量 10–141 不等，小分区结论不稳。
-- ============================================================


-- ============================================================
-- 【语句 1】按二级分区算 收藏率 / 点赞率 / 两者比值
-- 结构说明：这条没有窗口函数、不算中位数，就是最普通的 GROUP BY 聚合。
--   为什么不用中位数？因为"率"本身已经是标准化的比例，直接取平均就够了。
-- ============================================================
SELECT
    sub_zone,                                                          -- 维度：二级分区名

    COUNT(*) AS n,                                                      -- 该分区样本量

    -- 收藏率：先逐条算 (收藏/播放)，再对所有条取平均，×100 转百分比
    -- NULLIF(view_cnt, 0)：播放为 0 时返回 NULL，避免"除以零"
    ROUND(AVG(fav_cnt / NULLIF(view_cnt, 0)) * 100, 2) AS 收藏率pct,

    -- 点赞率：同样的算法
    ROUND(AVG(like_cnt / NULLIF(view_cnt, 0)) * 100, 2) AS 点赞率pct,

    -- 核心发现：收藏率 ÷ 点赞率。>1 = "存的人比赞的人多"
    ROUND(AVG(fav_cnt / NULLIF(view_cnt, 0))
          / NULLIF(AVG(like_cnt / NULLIF(view_cnt, 0)), 0), 2) AS 收藏点赞比

FROM video
WHERE is_duration_outlier = 0     -- 排除 >3 小时的直播回放/课程合集
  AND view_cnt > 1000             -- 排除极小播放（否则 1播放/1收藏 = 100%，会毁掉平均）
GROUP BY sub_zone                 -- 每个分区压成一行
HAVING COUNT(*) >= 10             -- 只保留样本 >=10 的分区
ORDER BY 收藏点赞比 DESC;          -- 比值最高的在最上面（职业职场应该第一）


-- ============================================================
-- 【语句 2】粗粒度对比：职业职场 vs 其他分区
-- 目的：语句 1 有 7 行不好一眼看出差异，压成 2 行后一目了然。
-- 技巧：用 CASE WHEN 在 GROUP BY 里"造"出一个二分类维度。
-- ============================================================
SELECT
    CASE WHEN sub_zone = '职业职场' THEN '1_职业职场'
         ELSE '2_其他分区' END AS 分组,                                  -- 造二分类维度（前缀保证排序）

    COUNT(*) AS n,
    ROUND(AVG(fav_cnt / NULLIF(view_cnt, 0)) * 100, 2)  AS 收藏率pct,
    ROUND(AVG(like_cnt / NULLIF(view_cnt, 0)) * 100, 2) AS 点赞率pct,
    ROUND(AVG(fav_cnt / NULLIF(view_cnt, 0))
          / NULLIF(AVG(like_cnt / NULLIF(view_cnt, 0)), 0), 2) AS 收藏点赞比

FROM video
WHERE is_duration_outlier = 0
  AND view_cnt > 1000
GROUP BY 分组                     -- MySQL 允许 GROUP BY 直接用 SELECT 里定义的别名
ORDER BY 分组;


-- ============================================================
-- 【语句 3】延伸检验：5 个关键词之间，收藏率有没有差异？
-- 思路：如果"职场内容被当工具收藏"成立，偏"方法/技能"的选题
--       （简历修改、职场沟通）收藏率应高于偏"资讯/情绪"的（转行、求职面试）。
-- 这是对同一个假设的"二次检验"——结论正负都能写进报告。
-- ============================================================
SELECT
    source_keyword,
    COUNT(*) AS n,
    ROUND(AVG(fav_cnt / NULLIF(view_cnt, 0)) * 100, 2)  AS 收藏率pct,
    ROUND(AVG(like_cnt / NULLIF(view_cnt, 0)) * 100, 2) AS 点赞率pct
FROM video
WHERE is_duration_outlier = 0
  AND view_cnt > 1000
  AND source_keyword LIKE 'kw:%'   -- 只看关键词采集的数据（采集方式一致，可比）
GROUP BY source_keyword
ORDER BY 收藏率pct DESC;
